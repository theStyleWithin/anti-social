#!/usr/bin/env python3
"""Builds consoles/common/font.h: an 8x16 bitmap font for the console apps, rendered from GNU Unifont
(a bitmap font, GPL-2.0-or-later with a font-embedding exception, also under the SIL OFL).
Usage: python3 tools/build-console-font.py /path/to/unifont.otf"""
import sys, os
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/unifont/unifont_jp.otf'
font = ImageFont.truetype(path, 16)
# ASCII first, then a few symbols the apps use; the C++ side maps these code points to glyph numbers
symbols = [0x25B2, 0x25BC, 0x25C0, 0x25B6, 0x25CB, 0x25CF, 0x21E7, 0x232B, 0x21B5, 0x25C6, 0x266A, 0x2190, 0x2191, 0x2192, 0x2193, 0x00D7, 0x00F7, 0x2212, 0x00B1, 0x221A]
cps = list(range(32, 127)) + symbols
rows = []
for cp in cps:
    im = Image.new('1', (8, 16), 0); d = ImageDraw.Draw(im)
    d.text((0, 0), chr(cp), font=font, fill=1)
    px = im.load(); r = [sum((1 << (7 - x)) for x in range(8) if px[x, y]) for y in range(16)]
    if cp > 32 and not any(r): raise SystemExit('missing glyph U+%04X' % cp)
    rows.append(r)
out = os.path.join(os.path.dirname(__file__), '..', 'consoles', 'common', 'font.h')
with open(out, 'w') as f:
    f.write('// Generated by tools/build-console-font.py from GNU Unifont (GPL-2.0-or-later with font exception / SIL OFL). Do not edit.\n#pragma once\n#include <stdint.h>\n')
    f.write('static const int kFontFirstSymbol = 95;  // glyph numbers 0..94 are ASCII 32..126\n')
    f.write('static const uint16_t kFontSymbols[] = {%s};\n' % ','.join('0x%04X' % c for c in symbols))
    f.write('static const int kFontSymbolCount = %d;\n' % len(symbols))
    f.write('static const uint8_t kFont[%d][16] = {\n' % len(cps))
    for r in rows: f.write('  {%s},\n' % ','.join('0x%02X' % b for b in r))
    f.write('};\n')
print(len(cps), 'glyphs ->', out)
