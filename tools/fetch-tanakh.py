#!/usr/bin/env python3
"""Rebuilds www/bible/*.js from Sefaria's public export. Both texts are public domain:
  English: The Holy Scriptures, A New Translation (JPS 1917)
  Hebrew:  Tanach with Nikkud (from the Westminster Leningrad Codex)
Run from the repo root: python3 tools/fetch-tanakh.py"""
import html, json, re, urllib.parse, urllib.request

BASE = "https://storage.googleapis.com/sefaria-export/json/Tanakh/"
EN = "The Holy Scriptures A New Translation JPS 1917.json"
HE = "Tanach with Nikkud.json"
BOOKS = {
  "Torah": ["Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy"],
  "Prophets": ["Joshua", "Judges", "I Samuel", "II Samuel", "I Kings", "II Kings", "Isaiah", "Jeremiah", "Ezekiel", "Hosea", "Joel", "Amos", "Obadiah", "Jonah", "Micah", "Nahum", "Habakkuk", "Zephaniah", "Haggai", "Zechariah", "Malachi"],
  "Writings": ["Psalms", "Proverbs", "Job", "Song of Songs", "Ruth", "Lamentations", "Ecclesiastes", "Esther", "Daniel", "Ezra", "Nehemiah", "I Chronicles", "II Chronicles"],
}

def get(section, book, lang, version):
    url = BASE + f"{section}/{urllib.parse.quote(book)}/{lang}/{urllib.parse.quote(version)}"
    return json.load(urllib.request.urlopen(url, timeout=120))

def clean(s):
    s = re.sub(r"<sup[^>]*>.*?</sup>|<i class=\"footnote\">.*?</i>", "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", "", s)
    s = html.unescape(s).replace(" ", " ").replace(" ", " ")
    s = re.sub(r"\{[^}]{1,3}\}", "", s)               # section markers like {פ} {ס}
    return re.sub(r"\s+", " ", s).strip()

def chapters(t):
    return [[clean(v) if isinstance(v, str) else "" for v in (ch if isinstance(ch, list) else [ch])] for ch in t]

en, he = [], []
for section, names in BOOKS.items():
    for name in names:
        e, h = get(section, name, "English", EN), get(section, name, "Hebrew", HE)
        assert e["license"] == "Public Domain" and h["license"] == "Public Domain", (name, e["license"], h["license"])
        ce, ch = chapters(e["text"]), chapters(h["text"])
        en.append({"n": name.replace("I ", "1 ", 1) if name.startswith("I ") and not name.startswith("II") and not name.startswith("Isa") else name, "s": section, "h": h["heTitle"], "c": ce})
        he.append({"c": ch})
        print(name, len(ce), "chapters", sum(map(len, ce)), "verses (en)", sum(map(len, ch)), "(he)")

# "I Samuel" -> "1 Samuel", "II Kings" -> "2 Kings"
for b in en:
    b["n"] = re.sub(r"^II ", "2 ", re.sub(r"^I (?=[A-Z])", "1 ", b["n"]))

def dump(path, var, obj):
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* Public domain. Generated by tools/fetch-tanakh.py; see the README for sources. */\n")
        f.write("window.BibleData = window.BibleData || {};\nBibleData[%s] = %s;\n" % (json.dumps(var), json.dumps(obj, ensure_ascii=False, separators=(",", ":"))))

dump("www/bible/jps1917.js", "jps1917", {"id": "jps1917", "lang": "en", "name": "Tanakh (JPS 1917, English)", "books": en})
dump("www/bible/tanakh-he.js", "tanakh-he", {"id": "tanakh-he", "lang": "he", "name": "Tanakh (Hebrew)", "books": he})
