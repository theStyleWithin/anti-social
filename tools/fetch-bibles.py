#!/usr/bin/env python3
"""Rebuilds www/bible/kjv.js and www/bible/web.js (the complete Bible, 66 books). Both are public domain:
  KJV: King James Version (1769 text), from github.com/thiagobodruk/bible
  WEB: World English Bible, from github.com/TehShrike/world-english-bible
Run from the repo root: python3 tools/fetch-bibles.py"""
import json, re, urllib.request

NAMES = ["Genesis","Exodus","Leviticus","Numbers","Deuteronomy","Joshua","Judges","Ruth","1 Samuel","2 Samuel","1 Kings","2 Kings","1 Chronicles","2 Chronicles","Ezra","Nehemiah","Esther","Job","Psalms","Proverbs","Ecclesiastes","Song of Solomon","Isaiah","Jeremiah","Lamentations","Ezekiel","Daniel","Hosea","Joel","Amos","Obadiah","Jonah","Micah","Nahum","Habakkuk","Zephaniah","Haggai","Zechariah","Malachi","Matthew","Mark","Luke","John","Acts","Romans","1 Corinthians","2 Corinthians","Galatians","Ephesians","Philippians","Colossians","1 Thessalonians","2 Thessalonians","1 Timothy","2 Timothy","Titus","Philemon","Hebrews","James","1 Peter","2 Peter","1 John","2 John","3 John","Jude","Revelation"]
get = lambda u: urllib.request.urlopen(u, timeout=120).read()
tidy = lambda s: re.sub(r"\s+", " ", s).strip()

def kjv():
    d = json.loads(get("https://raw.githubusercontent.com/thiagobodruk/bible/master/json/en_kjv.json").decode("utf-8-sig"))
    assert len(d) == 66
    return [[[tidy(v) for v in ch] for ch in b["chapters"]] for b in d]

def web():
    out = []
    for n in NAMES:
        items = json.loads(get("https://raw.githubusercontent.com/TehShrike/world-english-bible/master/json/" + n.lower().replace(" ", "") + ".json"))
        chs = {}
        for it in items:
            if it.get("verseNumber") and it.get("value") is not None and it.get("chapterNumber"):
                chs.setdefault(it["chapterNumber"], {}).setdefault(it["verseNumber"], []).append(it["value"])
        book = []
        for c in range(1, max(chs) + 1):
            vs = chs.get(c, {})
            book.append([tidy(" ".join(vs.get(v, []))) for v in range(1, (max(vs) if vs else 0) + 1)])
        out.append(book)
    return out

def dump(path, id_, name, books):
    for n, b in zip(NAMES, books):
        assert b and all(b), (id_, n, "has an empty chapter")
    obj = {"id": id_, "lang": "en", "name": name, "books": [{"n": n, "s": "Old Testament" if i < 39 else "New Testament", "c": c} for i, (n, c) in enumerate(zip(NAMES, books))]}
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* Public domain. Generated by tools/fetch-bibles.py; see the README for sources. */\n")
        f.write("window.BibleData = window.BibleData || {};\nBibleData[%s] = %s;\n" % (json.dumps(id_), json.dumps(obj, ensure_ascii=False, separators=(",", ":"))))
    print(id_, sum(len(c) for b in books for c in b), "verses,", sum(len(b) for b in books), "chapters")

dump("www/bible/kjv.js", "kjv", "King James Version", kjv())
dump("www/bible/web.js", "web", "World English Bible", web())
