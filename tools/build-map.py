#!/usr/bin/env python3
"""Builds www/map/world.js (country outlines and a list of cities) from Natural Earth, which is public domain
(naturalearthdata.com). Outlines come from the 1:50m countries, simplified and rounded to 0.01 degree.
Run from the repo root: python3 tools/build-map.py"""
import json, math, urllib.request

BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/"
get = lambda n: json.load(urllib.request.urlopen(BASE + n, timeout=300))

def rdp(pts, eps):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy) or 1e-12
        best, bi = -1, a
        for i in range(a + 1, b):
            d = abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / L
            if d > best: best, bi = d, i
        if best > eps:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def ring(r):
    r = [(x, y) for x, y in r]
    # a closed ring starts and ends at the same point, so split it at the farthest point before simplifying
    m = max(range(len(r)), key=lambda i: (r[i][0] - r[0][0]) ** 2 + (r[i][1] - r[0][1]) ** 2)
    pts = rdp(r[:m + 1], 0.02)[:-1] + rdp(r[m:], 0.02)
    out, last = [], None
    for x, y in pts:
        q = (round(x * 100), round(y * 100))
        if q != last: out.append(q); last = q
    if len(out) < 4: return None
    flat = []
    for q in out: flat += [q[0], q[1]]
    return flat

countries = []
for f in get("ne_50m_admin_0_countries.geojson")["features"]:
    p, g = f["properties"], f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    rings = []
    for poly in polys:
        r = ring(poly[0])               # outer boundary only; lakes and holes are not needed here
        if r: rings.append(r)
    if rings:
        name = p.get("NAME") or p.get("ADMIN")
        countries.append([name, p.get("ISO_A2") if p.get("ISO_A2") not in (None, "-99") else "", rings])
countries.sort(key=lambda c: c[0])
iso = {c[1]: i for i, c in enumerate(countries) if c[1]}

cities = []
for f in get("ne_10m_populated_places_simple.geojson")["features"]:
    p = f["properties"]
    pop = p.get("pop_max") or 0
    if pop < 60000 and not p.get("adm0cap"): continue
    cc = iso.get(p.get("iso_a2"), -1)
    cities.append([p.get("nameascii") or p.get("name"), cc, round(p["latitude"] * 100), round(p["longitude"] * 100), pop])
cities.sort(key=lambda c: -c[4])

with open("www/map/world.js", "w", encoding="utf-8") as f:
    f.write("/* Public domain (Natural Earth). Generated by tools/build-map.py. Coordinates are degrees x 100. */\n")
    f.write("window.WorldMap = " + json.dumps({"countries": countries, "cities": cities}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(countries), "countries,", sum(len(r) // 2 for c in countries for r in c[2]), "points,", len(cities), "cities")
